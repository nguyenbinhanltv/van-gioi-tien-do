// Prepares generated, git-ignored inputs for the Cocos project:
//   1. assets/scripts/vendor/vgtd.mjs (+ .d.mts)  <- esbuild bundle of @vgtd/shared + @vgtd/client-core + @vgtd/client-world + @vgtd/client-combat
//   2. assets/resources/world/*                 <- tilemap from @vgtd/procgen (npm run gen:tilemap)
//   3. assets/resources/dragonbones/viewer/*    <- DragonBones 5.5 test rig from @vgtd/dragonbones-testrig
//   4. assets/chibi/* + resources/world/chibi-index.json <- chibi runtime bundles (D71, scripts/chibi-bundles.mjs)
// Run: npm run prepare:assets -w client-cocos   (also invoked by build:web)
import { build } from 'esbuild';
import ts from 'typescript';
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareChibiBundles } from './chibi-bundles.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(root, '../..');

// 1. vendor bundle -----------------------------------------------------------
const vendorDir = join(root, 'assets/scripts/vendor');
mkdirSync(vendorDir, { recursive: true });
const bundled = await build({
  entryPoints: [join(root, 'vendor-src/entry.ts')],
  write: false,
  outfile: join(vendorDir, 'vgtd.mjs'),
  bundle: true,
  // @vgtd/character (and others) import the full @vgtd/shared index, which drags in ajv; resolve it to the engine-safe subset.
  alias: {
    '@vgtd/shared': join(root, 'vendor-src/shared-subset.ts'),
    // the full @vgtd/sim index imports skill data (ajv); the client only predicts movement
    '@vgtd/sim': join(root, 'vendor-src/sim-subset.ts'),
    '@vgtd/protocol': join(root, '../../packages/protocol/src/index.ts'),
  },
  format: 'esm',
  target: 'es2020',
  platform: 'neutral',
  sourcemap: false,
  banner: { js: '// GENERATED by apps/client-cocos/scripts/prepare.mjs - do not edit, do not commit.' },
  logLevel: 'error',
});
// Cocos runs a LOOSE Babel transform over every script under assets/ (this bundle included): there `[...set]` and
// `for (x of set)` only work for arrays, which silently breaks Set/Map code (e.g. @vgtd/character's paperdoll).
// So lower the bundle to ES5 ourselves with spec-compliant iteration helpers; Babel then has nothing left to break.
const lowered = ts.transpileModule(bundled.outputFiles[0].text, {
  fileName: 'vgtd.js',
  compilerOptions: {
    target: ts.ScriptTarget.ES5,
    module: ts.ModuleKind.ESNext,
    allowJs: true,
    downlevelIteration: true,
    importHelpers: false,
  },
}).outputText;
writeFileSync(join(vendorDir, 'vgtd.mjs'), lowered);
// Types come straight from the TypeScript sources: single source of truth, no copies.
writeFileSync(
  join(vendorDir, 'vgtd.d.mts'),
  [
    '// GENERATED - types re-exported from the workspace sources.',
    "export * as shared from '../../../vendor-src/shared-subset';",
    "export * as core from '../../../../../packages/client-core/src/index';",
    "export * as character from '../../../vendor-src/character-subset';",
    "export * as sim from '../../../vendor-src/sim-subset';",
    "export * as world from '../../../../../packages/client-world/src/index';",
    "export * as combat from '../../../../../packages/client-combat/src/index';",
    '',
  ].join('\n'),
);

// 2. tilemap -----------------------------------------------------------------
const procgen = join(repo, 'tools/procgen');
const out = join(procgen, 'out/tilemap');
// owner-provided Gemini art first (ground patches feed the tile generator below via `gen:tilemap --ground`, props / icons are copied in step 5);
// `--allow-missing`: without the LFS sources the tilemap stays procedural and the client keeps its placeholder props / text bag tiles
{
  const g = spawnSync(process.execPath, [join(procgen, 'scripts/gemini_assets.js'), '--allow-missing'], {
    stdio: 'inherit',
  });
  if (g.status !== 0) throw new Error('gen:gemini failed');
}
// always regenerate (0.6 s) so the copied tilemap can never be stale vs tools/procgen
{
  // Slice map = Son Mon (docs/04 section 5, docs/10 section 12): 256 x 256 tiles = 8 x 8 chunks, so the ChunkStreamer really
  // streams (keep window 7x7). `VGTD_MAP_TILES` overrides (e.g. 32 = the old single-chunk map). `--previewScale 0` skips
  // map_preview.png: nobody opens it here and drawing it costs ~1 minute on a 256 map.
  const tiles = String(Number(process.env.VGTD_MAP_TILES) || 256);
  const r = spawnSync(
    'npm',
    [
      'run',
      'gen:tilemap',
      '--',
      '--width',
      tiles,
      '--height',
      tiles,
      '--previewScale',
      '0',
      // VGTD_ZONES=0 builds the old 3-material map (A/B measurements); default: the four zones (D95, `gen:tilemap` has `--zones 1`)
      ...(process.env.VGTD_ZONES === '0' ? ['--zones', '0'] : []),
    ],
    { cwd: procgen, stdio: 'inherit', shell: true },
  );
  if (r.status !== 0) throw new Error('gen:tilemap failed');
}
const worldDir = join(root, 'assets/resources/world');
mkdirSync(worldDir, { recursive: true });
copyFileSync(join(out, 'map.json'), join(worldDir, 'iso-map.json'));
copyFileSync(join(out, 'tileset.json'), join(worldDir, 'iso-tileset.json'));
copyFileSync(join(out, 'tileset.png'), join(worldDir, 'iso-tileset.png'));
// 3. DragonBones 5.5 test rig for the animation viewer (tools/dragonbones-testrig) -> assets/resources/dragonbones/viewer
rmSync(join(root, 'assets/resources/viewer'), { recursive: true, force: true }); // old Spine-era location
rmSync(join(root, 'assets/resources/viewer.meta'), { force: true });
const viewerDir = join(root, 'assets/resources/dragonbones/viewer');
rmSync(viewerDir, { recursive: true, force: true });
mkdirSync(viewerDir, { recursive: true });
const gen = spawnSync(process.execPath, [join(repo, 'tools/dragonbones-testrig/scripts/generate.mjs'), viewerDir], {
  stdio: 'inherit',
});
if (gen.status !== 0) throw new Error('dragonbones-testrig generation failed');
// 4. chibi runtime bundles (D71): per-direction Asset Bundles with tiers and clip groups, compress presets in the metas
prepareChibiBundles({ root, repo });
// 5. owner-provided Gemini props + item icons (assets-src/gemini, Git LFS): keyed / trimmed / packed by tools/procgen, copied next to
// the tilemap. `--allow-missing`: without the LFS sources the client falls back to its placeholder props and text bag tiles.
{
  const gdir = join(procgen, 'out/gemini');
  for (const f of [
    'gemini.json',
    'atl_prop_2x_0.png',
    'atl_prop_1x_0.png',
    'atl_gicon_2x_0.png',
    'atl_gicon_1x_0.png',
    'atl_skill_2x_0.png',
    'atl_skill_1x_0.png',
    'atl_ui_2x_0.png',
    'atl_ui_1x_0.png',
  ])
    rmSync(join(worldDir, f), { force: true }); // never leave stale art behind
  if (existsSync(join(gdir, 'gemini.json'))) {
    copyFileSync(join(gdir, 'gemini.json'), join(worldDir, 'gemini.json'));
    const sidecar = JSON.parse(readFileSync(join(gdir, 'gemini.json'), 'utf8'));
    for (const pages of Object.values(sidecar.atlases))
      for (const p of pages) copyFileSync(join(gdir, 'atlas', p.file), join(worldDir, p.file));
  }
}
console.log('prepared vendor bundle + tilemap + DragonBones test rig + chibi bundles + gemini props');
