// Prepares generated, git-ignored inputs for the Cocos project:
//   1. assets/scripts/vendor/vgtd.mjs (+ .d.mts)  <- esbuild bundle of @vgtd/shared + @vgtd/client-core
//   2. assets/resources/world/*                 <- tilemap from @vgtd/procgen (npm run gen:tilemap)
// Run: npm run prepare:assets -w client-cocos   (also invoked by build:web)
import { build } from 'esbuild';
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(root, '../..');

// 1. vendor bundle -----------------------------------------------------------
const vendorDir = join(root, 'assets/scripts/vendor');
mkdirSync(vendorDir, { recursive: true });
await build({
  entryPoints: [join(root, 'vendor-src/entry.ts')],
  outfile: join(vendorDir, 'vgtd.mjs'),
  bundle: true,
  format: 'esm',
  target: 'es2020',
  platform: 'neutral',
  sourcemap: false,
  banner: { js: '// GENERATED by apps/client-cocos/scripts/prepare.mjs - do not edit, do not commit.' },
  logLevel: 'error',
});
// Types come straight from the TypeScript sources: single source of truth, no copies.
writeFileSync(
  join(vendorDir, 'vgtd.d.mts'),
  [
    '// GENERATED - types re-exported from the workspace sources.',
    "export * as shared from '../../../vendor-src/shared-subset';",
    "export * as core from '../../../../../packages/client-core/src/index';",
    '',
  ].join('\n'),
);

// 2. tilemap -----------------------------------------------------------------
const procgen = join(repo, 'tools/procgen');
const out = join(procgen, 'out/tilemap');
// always regenerate (0.6 s) so the copied tilemap can never be stale vs tools/procgen
{
  const r = spawnSync('npm', ['run', 'gen:tilemap'], { cwd: procgen, stdio: 'inherit', shell: true });
  if (r.status !== 0) throw new Error('gen:tilemap failed');
}
const worldDir = join(root, 'assets/resources/world');
mkdirSync(worldDir, { recursive: true });
copyFileSync(join(out, 'map.json'), join(worldDir, 'iso-map.json'));
copyFileSync(join(out, 'tileset.json'), join(worldDir, 'iso-tileset.json'));
copyFileSync(join(out, 'tileset.png'), join(worldDir, 'iso-tileset.png'));
console.log('prepared vendor bundle + tilemap assets');
