import { JobQueue } from './ChibiQueue';
import { AssetManager, JsonAsset, assetManager, dragonBones, resources, sys } from 'cc';

/**
 * Runtime loading of chibi armatures from per-direction Asset Bundles (D71).
 *
 *   bundle `chibi-<class>-<dir>` / `<tier>/<stem>_<DIR>_ske|tex` (+ `_loco<n>_tex`, `_rest<n>_tex` extra pages)
 *
 * - tier `full` = exported pixels (local player on desktop), `1x` = half resolution (mobile, every other actor);
 * - group `loco` (idle/walk/run) is loaded with the rig, group `rest` (combat, emote, ...) only on demand;
 * - a small queue limits concurrent downloads and holds background work (priority >= 1: NPCs, prefetch) back until
 *   `chibiStreamer.openBackground()`, so the first download is the player's own class locomotion only.
 * Bundles, rigs and groups are cached and shared by every actor of the same class/direction/tier.
 */
export type ChibiTier = 'full' | '1x';
export type ChibiGroup = 'loco' | 'rest';

export interface ChibiDirectionIndex {
  /** Atlas asset names per tier and group; the first `loco` page is the rig's main atlas (`<stem>_<DIR>_tex`). */
  readonly pages: Record<ChibiTier, Record<ChibiGroup, readonly string[]>>;
}
export interface ChibiIndex {
  readonly classes: Record<string, { readonly stem: string; readonly directions: Record<string, ChibiDirectionIndex> }>;
}

let indexPromise: Promise<ChibiIndex> | null = null;
/** `resources/world/chibi-index.json`, generated by `scripts/prepare.mjs` from the bundles it built. */
export function loadChibiIndex(): Promise<ChibiIndex> {
  if (!indexPromise) {
    indexPromise = new Promise<ChibiIndex>((resolve, reject) =>
      resources.load('world/chibi-index', JsonAsset, (err, asset) =>
        err || !asset
          ? reject(err ?? new Error('chibi-index missing: run prepare:assets'))
          : resolve(asset.json as unknown as ChibiIndex),
      ),
    );
    indexPromise.catch(() => (indexPromise = null));
  }
  return indexPromise;
}

/**
 * `?restier=full|1x` forces a tier. Default: `full` only for the local player on desktop, `1x` for everything else
 * (mobile, NPCs, other players, distant actors).
 */
export function chibiTierFor(local: boolean): ChibiTier {
  const forced = typeof location !== 'undefined' ? new URLSearchParams(location.search).get('restier') : null;
  if (forced === '1x') return '1x';
  if (forced === 'full') return local ? 'full' : '1x';
  return local && !sys.isMobile ? 'full' : '1x';
}

// ---- download queue (ChibiQueue.ts: priorities, background gate, promotion of queued jobs) ----------------------
export const chibiStreamer = new JobQueue();

// ---- bundles, rigs, groups -------------------------------------------------------------------------------------
const bundles = new Map<string, Promise<AssetManager.Bundle>>();
function loadBundle(name: string): Promise<AssetManager.Bundle> {
  let b = bundles.get(name);
  if (!b) {
    b = new Promise((resolve, reject) =>
      assetManager.loadBundle(name, (err, bundle) =>
        err || !bundle ? reject(err ?? new Error(`bundle ${name}`)) : resolve(bundle),
      ),
    );
    bundles.set(name, b);
    b.catch(() => bundles.delete(name));
  }
  return b;
}
function loadIn<T>(bundle: AssetManager.Bundle, path: string, type: new () => T): Promise<T> {
  return new Promise((resolve, reject) =>
    bundle.load(path, type as never, (err: Error | null, asset: unknown) =>
      err || !asset ? reject(err ?? new Error(`cannot load ${bundle.name}/${path}`)) : resolve(asset as T),
    ),
  );
}

export interface ChibiRig {
  readonly ske: dragonBones.DragonBonesAsset;
  readonly tex: dragonBones.DragonBonesAtlasAsset;
  readonly tier: ChibiTier;
  /** Groups whose atlas pages are registered with the DragonBones factory (`loco` always, `rest` after `loadGroup`). */
  readonly groups: Set<ChibiGroup>;
  readonly bundle: string;
  readonly pages: Record<ChibiGroup, readonly string[]>;
  readonly pending: Map<ChibiGroup, Promise<void>>;
}
const rigs = new Map<string, Promise<ChibiRig>>();

export const chibiBundleName = (classId: string, dir: string): string => `chibi-${classId}-${dir.toLowerCase()}`;

/** Loads (once) the rig of a direction: skeleton + `loco` atlas pages. */
export function loadChibiRig(
  index: ChibiIndex,
  classId: string,
  dir: string,
  tier: ChibiTier,
  priority: number,
): Promise<ChibiRig> {
  const key = `${classId}|${dir}|${tier}`;
  let hit = rigs.get(key);
  if (hit) {
    // already requested (maybe only queued at background priority): a more urgent caller promotes the queued job
    chibiStreamer.promote(`rig ${key}`, priority);
  } else {
    const entry = index.classes[classId];
    const di = entry?.directions[dir];
    if (!entry || !di) return Promise.reject(new Error(`no chibi bundle for ${classId}/${dir}`));
    const bundle = chibiBundleName(classId, dir);
    const base = `${tier}/${entry.stem}_${dir}`;
    const pages = di.pages[tier];
    hit = chibiStreamer.enqueue(`rig ${key}`, priority, `rig ${key}`, async () => {
      const b = await loadBundle(bundle);
      const [ske, tex] = await Promise.all([
        loadIn(b, `${base}_ske`, dragonBones.DragonBonesAsset),
        loadIn(b, `${base}_tex`, dragonBones.DragonBonesAtlasAsset),
      ]);
      const rig: ChibiRig = { ske, tex, tier, groups: new Set(['loco']), bundle, pages, pending: new Map() };
      await registerPages(rig, b, pages.loco.slice(1));
      return rig;
    });
    rigs.set(key, hit);
    hit.catch(() => rigs.delete(key));
  }
  return hit;
}

/** Loads the pages of a clip group (`rest`: combat, emote, ...) and registers them; resolves when frames can render. */
export function loadChibiGroup(rig: ChibiRig, group: ChibiGroup, priority: number): Promise<void> {
  if (rig.groups.has(group)) return Promise.resolve();
  const key = `group ${rig.bundle}/${rig.tier}/${group}`;
  let p = rig.pending.get(group);
  if (p) {
    chibiStreamer.promote(key, priority);
  } else {
    p = chibiStreamer.enqueue(key, priority, key, async () => {
      const b = await loadBundle(rig.bundle);
      await registerPages(rig, b, rig.pages[group]);
      rig.groups.add(group);
    });
    rig.pending.set(group, p);
    p.catch(() => rig.pending.delete(group));
  }
  return p;
}

async function registerPages(rig: ChibiRig, b: AssetManager.Bundle, names: readonly string[]): Promise<void> {
  if (names.length === 0) return;
  const factory = dragonBones.CCFactory.getInstance();
  rig.tex.init(factory);
  const extras = await Promise.all(names.map((n) => loadIn(b, `${rig.tier}/${n}`, dragonBones.DragonBonesAtlasAsset)));
  for (const extra of extras) {
    const data = JSON.parse(extra.atlasJson) as { name: string; imagePath: string };
    const registered = factory.getTextureAtlasData(rig.tex.uuid) ?? [];
    if (!registered.some((p) => p.name === data.name && p.imagePath === data.imagePath))
      factory.parseTextureAtlasData(data, extra.texture, rig.tex.uuid);
  }
}
