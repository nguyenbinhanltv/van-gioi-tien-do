import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { decodePng, encodePng } from '@vgtd/rig';
import { cellHashes, repairCell } from '@vgtd/sprite';
const [dir,clipName,cellList]=process.argv.slice(2),cells=cellList!.split(',').map(Number);
const attempt=Number(process.argv[5]??2);
const base=join(process.cwd(),'assets-src/placeholder/the-tu-sprites-v1',dir!);
const project=JSON.parse(readFileSync(join(base,'project.json'),'utf8'));
const clip=project.clips.find((c:any)=>c.name===clipName),grid={cols:clip.cols,rows:Math.ceil(clip.frames/clip.cols)};
const sourcePath=attempt===2?`raw/${clipName}.attempt1.png`:`raw/${clipName}.attempt${attempt-1}.selected.png`;
const originalBytes=readFileSync(join(base,sourcePath)),original=decodePng(originalBytes);
const donor=decodePng(readFileSync(join(base,`raw/${clipName}.attempt${attempt}.edited.png`)));
let selected=original;for(const cell of cells)selected=repairCell(selected,donor,grid,cell).image;
const before=cellHashes(original,grid),after=cellHashes(selected,grid);
if(before.some((h,i)=>!cells.includes(i)&&h!==after[i]))throw new Error('Unselected cell changed');
const selectedBytes=encodePng(selected);writeFileSync(join(base,`sheets/${clipName}.png`),selectedBytes);
const proof={clip:clipName,dir,method:'Public repairCell: selected AI donor cells only, no per-frame scaling or height fitting',cells0:cells,unchangedOtherCells:clip.frames-cells.length,originalDimensions:[original.width,original.height],donorDimensions:[donor.width,donor.height],before,after,rawSource:sourcePath,donor:`raw/${clipName}.attempt${attempt}.edited.png`,selected:`sheets/${clipName}.png`,sourceSha256:createHash('sha256').update(originalBytes).digest('hex'),selectedSha256:createHash('sha256').update(selectedBytes).digest('hex')};
writeFileSync(join(base,`raw/${clipName}.attempt${attempt}.repair-proof.json`),JSON.stringify(proof,null,2)+'\n');
console.log(dir,clipName,proof.unchangedOtherCells,'unselected cells byte-identical');
